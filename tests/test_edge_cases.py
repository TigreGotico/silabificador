"""Edge cases of Portuguese syllabification, with every accepted split cited.

``edge_cases.json`` holds the words where the grammars or the dictionaries
disagree, or where one source is wrong. Each entry lists every split that a
cited source accepts -- Cunha & Cintra accept both ``a-pto`` and ``ap-to`` -- so
the engine is correct when its split is any one of them. The expected values
come from the sources named in the file, never from the engine.

An entry with ``engine_gap`` is a case the engine does not get right yet. It is
a strict xfail: when the engine is fixed, the test fails until the marker goes.
"""
import json
import pathlib
from collections import Counter

import pytest

from silabificador import syllabify

DATA = json.loads((pathlib.Path(__file__).parent / "edge_cases.json").read_text(encoding="utf-8"))
ENTRIES = DATA["entries"]
CLASSES = ("medial cluster", "prefix seam", "productive prefix", "hiatus vs diphthong",
           "AO90 hyphen", "error in one source", "stress and hiatus")


def _params():
    for entry in ENTRIES:
        marks = []
        if "engine_gap" in entry:
            marks.append(pytest.mark.xfail(strict=True, reason=entry["engine_gap"]))
        yield pytest.param(entry, id=entry["word"], marks=marks)


@pytest.mark.parametrize("entry", list(_params()))
def test_engine_split_is_one_a_source_accepts(entry):
    accepted = {a["split"] for a in entry["accepted"]}
    assert ".".join(syllabify(entry["word"])) in accepted


@pytest.mark.parametrize("entry", ENTRIES, ids=[e["word"] for e in ENTRIES])
def test_every_split_is_cited_and_spells_its_word(entry):
    known = {name.split(" Base")[0] for name in DATA["sources"]}
    for split in entry["accepted"] + entry.get("rejected", []):
        assert split["split"].replace(".", "") == entry["word"]
        assert split["sources"] and split["reason"]
        for source in split["sources"]:
            assert source == "silabificador dev" or source.split(" p. ")[0].split(" Base")[0] in known


def test_no_rejected_split_is_also_accepted():
    for entry in ENTRIES:
        accepted = {a["split"] for a in entry["accepted"]}
        assert not accepted & {r["split"] for r in entry.get("rejected", ())}, entry["word"]


def test_every_class_is_covered():
    counts = Counter(e["class"] for e in ENTRIES)
    assert set(counts) == set(CLASSES)
    assert all(counts[c] >= 3 for c in CLASSES), counts


def test_words_with_several_accepted_splits_are_present():
    # The point of the format: a word can be right two ways.
    multi = [e["word"] for e in ENTRIES if len(e["accepted"]) > 1]
    assert {"apto", "digno", "ritmo", "glória", "sublinhar", "abrupto", "ciberespaço"} <= set(multi)


def test_the_portal_is_never_the_only_source_of_an_accepted_split():
    # The Portal's data are generated by rule; its presentation page is prose
    # written by its authors and may stand alone.
    for entry in ENTRIES:
        for split in entry["accepted"]:
            assert split["sources"] != ["Portal"], (entry["word"], split["split"])
