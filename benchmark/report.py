"""Full-dataset scoreboard and error taxonomy.

    python -m benchmark.report [--examples N] [--parquet PATH]
                               [--enwiktionary PATH] [--ptwiktionary PATH] [--cache DIR]

Scores the engine on every scoreable word of every tier -- no sampling, no caps
-- and buckets every failure by cause, so residual errors can be described
instead of patched. A prediction is correct when it is one of the accepted
splits. The Wiktionary dumps are downloaded into ``--cache`` unless their paths
are given.
"""
from __future__ import annotations

import argparse
import collections
import json
import os
from typing import Dict, List, Tuple

from silabificador import stressed_index, syllabify

from . import gold as goldlib
from . import stress_gold as stresslib
from . import wiktionary
from .gold import Accepted, GoldSet, Split, accepts, fuse

EDGE_CASES = os.path.join(os.path.dirname(os.path.dirname(__file__)), "tests", "edge_cases.json")

VOWELS = "aeiouáéíóúâêîôûàãẽĩõũäëïöüy"


def _score(entries: Dict[str, Accepted]) -> Tuple[int, int, List[Tuple[str, Split, Split]]]:
    """Correct count and every failure, as ``(word, expected, predicted)``.

    A prediction is correct when it is one of the accepted splits. A failure is
    reported against the first accepted split.
    """
    correct = 0
    failures = []
    for word, accepted in entries.items():
        predicted = tuple(syllabify(word))
        # Compared after fusing across separators: the engine returns syllables,
        # the dictionaries return hyphenation points. See gold.fuse.
        if accepts(accepted, predicted):
            correct += 1
        else:
            failures.append((word, min(accepted), fuse(predicted)))
    return correct, len(entries), failures


def edge_cases() -> Dict[str, Accepted]:
    """The curated edge cases: word -> every split a cited source accepts."""
    with open(EDGE_CASES, encoding="utf-8") as handle:
        entries = json.load(handle)["entries"]
    return {e["word"]: frozenset(fuse(tuple(a["split"].split("."))) for a in e["accepted"])
            for e in entries}


def classify(word: str, expected: Split, predicted: Split) -> str:
    """Bucket a failure by what the engine got wrong."""
    if "".join(predicted) != word:
        # The output does not spell the input. Always a bug, never a
        # convention difference.
        return "corruption (output does not reconstruct the word)"

    if len(predicted) > len(expected):
        return "over-split (predicted hiatus, gold has diphthong)"
    if len(predicted) < len(expected):
        return "under-split (predicted diphthong, gold has hiatus)"

    # Same syllable count: a boundary sits in the wrong place. Locate the first
    # divergent boundary and name the material it falls in.
    boundary = 0
    for exp, pred in zip(expected, predicted):
        if exp != pred:
            break
        boundary += len(exp)
    left = word[max(0, boundary - 2):boundary]
    right = word[boundary:boundary + 2]
    around = left + right
    if any(c not in VOWELS for c in around if c.isalpha()):
        cluster = "".join(c for c in around if c.isalpha() and c not in VOWELS)
        return f"boundary in consonant cluster ({cluster or '?'})"
    return "boundary between vowels"


def taxonomy(failures: List[Tuple[str, Split, Split]]) -> collections.Counter:
    return collections.Counter(classify(w, e, p) for w, e, p in failures)


def _row(name: str, correct: int, total: int) -> str:
    pct = 100.0 * correct / total if total else 0.0
    return f"| {name} | {pct:.2f}% | {correct:,} / {total:,} |"


def write_markdown(path: str, gold: GoldSet, scores: List[Tuple[str, int, int]],
                   stress: Tuple[int, int], self_check: Tuple[int, int],
                   round_trip: Tuple[int, int]) -> None:
    """Write the scoreboard as the ``docs/accuracy.md`` page."""
    lines = [
        "# Accuracy",
        "",
        "Generated by `python -m benchmark.report --markdown docs/accuracy.md`.",
        "Do not edit this page by hand. The gold and the method are described in",
        "the [README](../README.md#accuracy).",
        "",
        "## Syllabification",
        "",
        f"The gold set holds the {len(gold.agreement):,} words on which two or more",
        "human-edited sources (Infopédia, en.wiktionary, pt.wiktionary) give the",
        "same split. A prediction is correct when it is one of the accepted splits.",
        "The Portal da Língua Portuguesa is generated by rule and is scored as its",
        "own tier, never as gold.",
        "",
        "| set | accepted match | |",
        "|---|---|---|",
        *(_row(name, correct, total) for name, correct, total in scores),
        "",
        f"{round_trip[0]:,} of {round_trip[1]:,} scoreable words reconstruct exactly.",
        "",
        "## Stress",
        "",
        "| | | |",
        "|---|---|---|",
        _row("stress accuracy", *stress),
        _row("gold self-check", *self_check),
        "",
        "",
        "---",
        "[← Advanced](advanced.md) · [Home](../README.md)",
        "",
    ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parquet", help="local parquet instead of the HF download")
    parser.add_argument("--enwiktionary", help="local Kaikki en.wiktionary Portuguese JSONL(.gz)")
    parser.add_argument("--ptwiktionary", help="local pt.wiktionary pages-articles XML(.bz2) dump")
    parser.add_argument("--cache", default=os.path.expanduser("~/.cache/silabificador"),
                        help="where the Wiktionary dumps are downloaded")
    parser.add_argument("--examples", type=int, default=5, help="failures to print per bucket")
    parser.add_argument("--markdown", help="also write the scoreboard to this markdown file")
    args = parser.parse_args()

    enwikt = args.enwiktionary or wiktionary.download(wiktionary.ENWIKT_URL, args.cache)
    ptwikt = args.ptwiktionary or wiktionary.download(wiktionary.PTWIKT_URL, args.cache)
    gold = goldlib.load(args.parquet, enwikt, ptwikt)

    print("PROVENANCE")
    for line in goldlib.summary(gold):
        print("  " + line)

    print("\nSCOREBOARD (prediction is one of the accepted splits; full sets, no sampling)")
    sets = [("edge cases (cited)", edge_cases()), *gold.tiers()]
    kept: Dict[str, List[Tuple[str, Split, Split]]] = {}
    scores: List[Tuple[str, int, int]] = []
    for name, entries in sets:
        correct, total, failures = _score(entries)
        kept[name] = failures
        scores.append((name, correct, total))
        pct = 100.0 * correct / total if total else 0.0
        print(f"  {name:<28} {pct:6.2f}%   {correct:>6}/{total:<6}")

    # The taxonomy is printed for the gold and for the single-source tiers,
    # where most of the unverified mass lives.
    for name in ("edge cases (cited)", "agreement (gold)", "infopedia-only", "michaelis-only",
                 "wiktionary-only"):
        failures = kept[name]
        print(f"\nERROR TAXONOMY -- {name}: {len(failures)} failures")
        by_bucket: Dict[str, List] = collections.defaultdict(list)
        for word, expected, predicted in failures:
            by_bucket[classify(word, expected, predicted)].append((word, expected, predicted))
        for bucket, count in taxonomy(failures).most_common():
            share = 100.0 * count / len(failures) if failures else 0.0
            print(f"  {count:>5}  ({share:4.1f}%)  {bucket}")
            for word, expected, predicted in sorted(by_bucket[bucket])[:args.examples]:
                print(f"           {word:<24} gold={'.'.join(expected):<26} got={'.'.join(predicted)}")

    print("\nSTRESS (independent gold: the lexicon's IPA, which the engine never reads)")
    stress = stresslib.load(args.parquet)
    agree, checked, _ = stresslib.self_check(stress)
    print(f"  gold                {len(stress):>6} words   "
          f"(EP only; IPA and spelling verified to align)")
    print(f"  gold self-check     {100.0 * agree / checked:6.2f}%   {agree}/{checked}   "
          f"on simple words, the written accent IS the stress -- and it agrees")

    correct = sum(1 for word, index in stress.items() if stressed_index(word) == index)
    print(f"  stress accuracy     {100.0 * correct / len(stress):6.2f}%   {correct}/{len(stress)}")

    wrong = [(w, i) for w, i in stress.items() if stressed_index(w) != i]
    endings = collections.Counter(w[-2:] for w, _ in wrong)
    print(f"  {len(wrong)} wrong; commonest endings: "
          + ", ".join(f"-{e} ({n})" for e, n in endings.most_common(5)))
    for word, index in sorted(wrong)[:args.examples]:
        syllables = syllabify(word)
        got = stressed_index(word)
        print(f"           {word:<20} gold=[{syllables[index]}]  got=[{syllables[got]}]")

    print("\nROUND-TRIP INVARIANT (every scoreable word)")
    every = set().union(*gold.sources.values())
    broken = [w for w in every if "".join(syllabify(w)) != w]
    print(f"  {len(every) - len(broken)}/{len(every)} words reconstruct exactly; {len(broken)} corrupted")
    for word in sorted(broken)[:args.examples]:
        print(f"    {word:<24} -> {'.'.join(syllabify(word))}")

    if args.markdown:
        write_markdown(args.markdown, gold, scores, (correct, len(stress)),
                       (agree, checked), (len(every) - len(broken), len(every)))


if __name__ == "__main__":
    main()
